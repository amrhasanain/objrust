//! lib.rs — Library entry point: wires the four stages together.
//!
//! ```text
//!   .orst source
//!        │
//!        ▼  lexer.rs     text   -> tokens
//!        ▼  parser.rs    tokens -> items (raw Rust + class declarations)
//!        ▼  codegen.rs   items  -> plain Rust source
//!        ▼
//!   .rs source  ->  rustc / cargo as usual
//! ```
//!
//! Shared types live in `ast.rs` (the data model) and `error.rs`
//! (positions and errors).
//!
//! Typical use:
//!
//! ```
//! let rust = objective_rust::transpile("class A { x: i32, }").unwrap();
//! assert!(rust.contains("struct A"));
//! ```

pub mod ast;
pub mod codegen;
pub mod error;
pub mod lexer;
pub mod parser;

pub use error::{Error, Pos, Result};

/// First line of every generated file.
pub const HEADER: &str = "// Generated by orst (Objective-Rust transpiler). Do not edit by hand.\n";

/// Translate Objective-Rust source into Rust source.
pub fn transpile(src: &str) -> Result<String> {
    let tokens = lexer::lex(src)?;
    let items = parser::parse(tokens)?;
    let body = codegen::generate(&items)?;
    Ok(format!("{}{}", HEADER, body))
}
